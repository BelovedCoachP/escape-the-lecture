#!/usr/bin/env node
// Compiles /schema/vault-schema.json into a standalone browser ES module at
// /exemplar/js/validate-schema.js. This is the runtime half of the accessibility
// guarantee: the exemplar validates content client-side with zero runtime
// dependencies. Re-run whenever the schema changes.

import { readFileSync, writeFileSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020Module from "ajv/dist/2020.js";
import standaloneModule from "ajv/dist/standalone/index.js";
import * as esbuild from "esbuild";

const Ajv2020 = Ajv2020Module.default ?? Ajv2020Module;
const standaloneCode = standaloneModule.default ?? standaloneModule;

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(readFileSync(join(root, "schema", "vault-schema.json"), "utf8"));

const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  code: { source: true, esm: true },
});
const validate = ajv.compile(schema);

// The standalone code imports ajv runtime helpers by bare specifier;
// esbuild inlines them so the output runs in a browser with no resolver.
const tmp = join(root, "scripts", ".validator-src.mjs");
writeFileSync(tmp, standaloneCode(ajv, validate));

try {
  await esbuild.build({
    entryPoints: [tmp],
    bundle: true,
    format: "esm",
    outfile: join(root, "exemplar", "js", "validate-schema.js"),
    banner: {
      js: "// GENERATED by scripts/build-validator.mjs from schema/vault-schema.json. Do not edit by hand.",
    },
  });
} finally {
  rmSync(tmp, { force: true });
}

console.log("Generated exemplar/js/validate-schema.js");
